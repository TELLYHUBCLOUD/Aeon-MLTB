async def apply_font_style(text, style_name):
    """
    Apply a font style to text.
    Supports basic HTML tags and some stylized unicode fonts.
    """
    style_name = style_name.lower()
    
    # Check for basic HTML styles
    if style_name in FONT_STYLES:
        start, end = FONT_STYLES[style_name]
        return f"{start}{text}{end}"
    
    # Check for stylized unicode fonts
    if style_name in FANCY_MAPS:
        char_map = FANCY_MAPS[style_name]
        return "".join(char_map.get(c, c) for c in text)
        
    return text
